#!/usr/bin/env python3
"""Play Legend of the Green Dragon - Resurrection on this computer with one command (Phase 4 task 3).

LOCAL USE ONLY, not for hosting. The game runs in Docker (local/compose.yaml): PHP 8.4 and MariaDB 11.4, the game
published only on 127.0.0.1, the database on an internal network with no published port.

    python3 scripts/local-play.py up                          start the game (installs it the first time)
    python3 scripts/local-play.py stop                        stop it; the game is kept
    python3 scripts/local-play.py wipe                        delete the game and its data volumes
    python3 scripts/local-play.py backup                      write a database backup to .local-play/backups/
    python3 scripts/local-play.py upgrade --dry-run           show what an upgrade would change
    python3 scripts/local-play.py upgrade --backup-confirmed  upgrade, after a backup
    python3 scripts/local-play.py restore FILE                put a backup back (replaces the game's database)

The first `up` generates the database and administrator credentials into the ignored .local-play/ directory
(owner-only files), and the install runs through scripts/install.php. A later `up` keeps the game: it never installs
again, and when the code is newer than the database it says so and stops, without upgrading. docs/MODERN-INSTALLATION.md,
"Play locally", has the details.
"""
import datetime
import os
from pathlib import Path
import re
import secrets
import shutil
import string
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
COMPOSE_FILE = ROOT / 'local' / 'compose.yaml'
STATE = ROOT / '.local-play'
PROJECT = 'resurrection-local'
CONFIG = '/config/dbconnect.php'
STOP = ['down', '--remove-orphans']
WIPE = ['down', '--volumes', '--remove-orphans']
UPGRADE_OPTIONS = ('--dry-run', '--backup-confirmed')
# setup.sh's exit codes.
CURRENT, INSTALLED, BEHIND = 0, 3, 10
# Runs inside the database container, which holds the password in its environment: it is never on this computer's
# command line or screen. MariaDB's clients read MYSQL_PWD.
DUMP = ('MYSQL_PWD="$MARIADB_PASSWORD" exec mariadb-dump --single-transaction --no-tablespaces '
        '--default-character-set=utf8mb4 -u"$MARIADB_USER" "$MARIADB_DATABASE"')
# Replaces the game's database with a backup: the database emptied and recreated, then the file loaded into it.
RESTORE = ('export MYSQL_PWD="$MARIADB_PASSWORD"; '
           'mariadb -u"$MARIADB_USER" -e "DROP DATABASE \\`$MARIADB_DATABASE\\`; CREATE DATABASE \\`$MARIADB_DATABASE\\` '
           'CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci" '
           '&& exec mariadb --default-character-set=utf8mb4 -u"$MARIADB_USER" "$MARIADB_DATABASE"')
LABEL = 'LOCAL USE ONLY: this game is for playing on this computer, not for hosting.'
ALPHABET = string.ascii_letters + string.digits


def secret(length):
    return ''.join(secrets.choice(ALPHABET) for _ in range(length))


def write_private(path, text):
    """Create a file owner-only from the start; never over an existing one."""
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, 'w') as file:
        file.write(text)


def ensure_credentials(state):
    """Generate the local credentials once. True when they were created, False when they already existed."""
    database, admin = state / 'database.env', state / 'admin.env'
    if database.exists() and admin.exists():
        return False
    if database.exists() or admin.exists():
        raise SystemExit(f'Only one of {database.name} and {admin.name} exists in {state}. Restore the other, or run '
                         '`python3 scripts/local-play.py wipe` to start a new game.')
    state.mkdir(mode=0o700, exist_ok=True)
    os.chmod(state, 0o700)
    values = {'MARIADB_DATABASE': 'resurrection', 'MARIADB_USER': 'resurrection',
              'MARIADB_PASSWORD': secret(32), 'MARIADB_ROOT_PASSWORD': secret(32)}
    write_private(database, '# Generated by scripts/local-play.py for the local game. Never commit or share.\n' +
                  ''.join(f'{key}={value}\n' for key, value in values.items()))
    write_private(admin, '# The local game\'s administrator, created at its install. Never commit or share.\n'
                  f'RESURRECTION_ADMIN_LOGIN=admin\nRESURRECTION_ADMIN_PASSWORD={secret(20)}\n')
    return True


def read_env(path):
    values = {}
    for line in path.read_text().splitlines():
        if line and not line.startswith('#'):
            key, _, value = line.partition('=')
            values[key] = value
    return values


def upgrade_command(arguments):
    """scripts/upgrade.php with exactly one of its two options and the local game's configuration."""
    if len(arguments) != 1 or arguments[0] not in UPGRADE_OPTIONS:
        raise SystemExit('Use `upgrade --dry-run` to see what would change, or `upgrade --backup-confirmed` after '
                         '`backup`.')
    return ['php', 'scripts/upgrade.php', arguments[0], CONFIG]


def compose(*arguments, check=True, **options):
    command = ['docker', 'compose', '--project-name', PROJECT, '-f', str(COMPOSE_FILE), *arguments]
    result = subprocess.run(command, **options)
    if check and result.returncode != 0:
        raise SystemExit(f'docker compose {arguments[0]} failed (exit {result.returncode}). See the output above.')
    return result


def preflight():
    if shutil.which('docker') is None:
        raise SystemExit('Docker is not installed or not on PATH. Install Docker (with Compose v2.24 or newer) first.')
    if subprocess.run(['docker', 'compose', 'version'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode != 0:
        raise SystemExit('Docker Compose v2 is not available (`docker compose version` failed). Start Docker, or '
                         'install Compose v2.24 or newer.')


def volume_exists(name):
    return subprocess.run(['docker', 'volume', 'inspect', f'{PROJECT}_{name}'], stdout=subprocess.DEVNULL,
                          stderr=subprocess.DEVNULL).returncode == 0


def port():
    value = os.environ.get('RESURRECTION_LOCAL_PORT', '8080')
    if not re.fullmatch(r'[1-9][0-9]{0,4}', value) or int(value) > 65535:
        raise SystemExit('RESURRECTION_LOCAL_PORT must be a port number.')
    return value


def banner(lines):
    rule = '=' * 78
    print('\n'.join(['', rule, *lines, rule, '']))


def upgrade_guidance():
    return ['The code is newer than this game\'s database: it needs an upgrade before it can be played.',
            'Nothing was upgraded, and the game is not started. To upgrade (docs/MODERN-INSTALLATION.md, "Play locally"):',
            '  1. Back up:    python3 scripts/local-play.py backup',
            '  2. Check:      python3 scripts/local-play.py upgrade --dry-run',
            '  3. Upgrade:    python3 scripts/local-play.py upgrade --backup-confirmed',
            '  4. Play:       python3 scripts/local-play.py up']


def up():
    preflight()
    url = f'http://127.0.0.1:{port()}/'
    complete = (STATE / 'database.env').exists() and (STATE / 'admin.env').exists()
    if not complete and (volume_exists('db') or volume_exists('config')):
        raise SystemExit(f'A local game exists in Docker, but its credentials are missing from {STATE}. Put them back, '
                         'or run `python3 scripts/local-play.py wipe` to delete that game and start a new one.')
    ensure_credentials(STATE)
    print(LABEL)
    compose('build', 'app')
    compose('up', '--detach', '--wait', 'db')
    state = compose('run', '--rm', 'setup', check=False).returncode
    if state not in (CURRENT, INSTALLED):
        # Nothing plays on a database the code cannot run on.
        compose('stop', 'app', 'cron')
        if state == BEHIND:
            banner([LABEL, '', *upgrade_guidance()])
        else:
            banner([LABEL, '', 'The game was not started: the setup refused or failed (the reason is above). Nothing was changed.',
                    'To put a backup back:   python3 scripts/local-play.py restore .local-play/backups/FILE.sql',
                    'To start a new game:    python3 scripts/local-play.py wipe, then up'])
        return 1
    compose('up', '--detach', '--wait', 'app', 'cron')
    admin = read_env(STATE / 'admin.env')
    if state == INSTALLED:
        login = ['A new game was installed. Administrator login (shown once; also kept in .local-play/admin.env):',
                 f'  Login:     {admin["RESURRECTION_ADMIN_LOGIN"]}',
                 f'  Password:  {admin["RESURRECTION_ADMIN_PASSWORD"]}']
    else:
        login = ['Your existing game was kept. The administrator login is in .local-play/admin.env.']
    banner(['Legend of the Green Dragon - Resurrection is running.', LABEL, '', f'Play:  {url}', '', *login, '',
            'Stop (keeps the game):  python3 scripts/local-play.py stop',
            'Wipe (deletes it):      python3 scripts/local-play.py wipe'])
    return 0


def stop():
    preflight()
    compose(*STOP)
    print('The local game is stopped. Its data is kept; `python3 scripts/local-play.py up` starts it again.')
    return 0


def wipe(arguments):
    preflight()
    if arguments not in ([], ['--yes']):
        raise SystemExit('Use `wipe`, or `wipe --yes` to skip the question.')
    if arguments != ['--yes']:
        answer = input('This deletes the local game: every account, character and setting, its database and its '
                       'generated credentials. Backups in .local-play/backups/ are kept. Type "wipe" to continue: ')
        if answer.strip() != 'wipe':
            print('Nothing was deleted.')
            return 1
    compose(*WIPE)
    for name in ('database.env', 'admin.env'):
        (STATE / name).unlink(missing_ok=True)
    if STATE.is_dir() and not any(STATE.iterdir()):
        STATE.rmdir()
    print('The local game, its data volumes and its credentials are deleted. `python3 scripts/local-play.py up` '
          'installs a new game.')
    return 0


def backup():
    preflight()
    if not (STATE / 'database.env').exists():
        raise SystemExit('There is no local game to back up.')
    compose('up', '--detach', '--wait', 'db')
    directory = STATE / 'backups'
    directory.mkdir(mode=0o700, exist_ok=True)
    path = directory / f'resurrection-{datetime.datetime.now(datetime.timezone.utc):%Y%m%d-%H%M%S}.sql'
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, 'wb') as file:
        result = compose('exec', '-T', 'db', 'sh', '-c', DUMP, check=False, stdout=file)
    with path.open('rb') as file:
        file.seek(max(0, path.stat().st_size - 512))
        complete = b'-- Dump completed' in file.read()
    if result.returncode != 0 or not complete:
        path.unlink()
        raise SystemExit('The backup failed (the reason is above); no backup file was kept.')
    print(f'Backup written: {path.relative_to(ROOT)} (keep it private: it holds every account).')
    return 0


def restore(arguments):
    preflight()
    if len(arguments) not in (1, 2) or (len(arguments) == 2 and arguments[1] != '--yes'):
        raise SystemExit('Use `restore .local-play/backups/FILE.sql`, or add --yes to skip the question.')
    path = Path(arguments[0]).resolve()
    if not (STATE / 'database.env').exists():
        raise SystemExit('There is no local game to restore into. `up` installs a new game first.')
    if not path.is_file():
        raise SystemExit('No such backup file.')
    with path.open('rb') as file:
        file.seek(max(0, path.stat().st_size - 512))
        if b'-- Dump completed' not in file.read():
            raise SystemExit('That file is not a complete backup (it has no "-- Dump completed" line). Nothing was changed.')
    if len(arguments) == 1:
        answer = input('This replaces everything in the local game\'s database with the backup. Type "restore" to continue: ')
        if answer.strip() != 'restore':
            print('Nothing was changed.')
            return 1
    compose('up', '--detach', '--wait', 'db')
    compose('stop', 'app', 'cron')
    with path.open('rb') as file:
        result = compose('exec', '-T', 'db', 'sh', '-c', RESTORE, check=False, stdin=file)
    if result.returncode != 0:
        raise SystemExit('The restore failed (the reason is above). The database may be empty or partly loaded: run '
                         'restore again with a complete backup, or wipe.')
    print('The backup is restored. Use the version of the game it was taken with, then: python3 scripts/local-play.py up')
    return 0


def upgrade(arguments):
    preflight()
    command = upgrade_command(arguments)
    if not (STATE / 'database.env').exists():
        raise SystemExit('There is no local game to upgrade.')
    compose('build', 'app')
    compose('up', '--detach', '--wait', 'db')
    if command[2] != '--dry-run':
        # No one plays and no maintenance runs while the database changes.
        compose('stop', 'app', 'cron')
    result = compose('run', '--rm', 'setup', *command, check=False)
    if result.returncode != 0:
        return result.returncode
    if command[2] != '--dry-run':
        print('Start the game again with: python3 scripts/local-play.py up')
    return 0


def main(arguments):
    commands = {'up': up, 'stop': stop}
    if arguments[:1] and arguments[0] in commands and len(arguments) == 1:
        return commands[arguments[0]]()
    if arguments[:1] == ['wipe']:
        return wipe(arguments[1:])
    if arguments == ['backup']:
        return backup()
    if arguments[:1] == ['restore']:
        return restore(arguments[1:])
    if arguments[:1] == ['upgrade']:
        return upgrade(arguments[1:])
    print(__doc__.split('\n\n')[2], file=sys.stderr)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
